"""TrueMark API.

Judge-friendly by design: every endpoint works with no login. A browser session is a "workspace"
(X-Workspace header, generated by the UI) with its own copy of the sample knowledge base."""
from __future__ import annotations

import asyncio
import json
import re
import time
from collections import defaultdict, deque
from contextlib import asynccontextmanager

from fastapi import FastAPI, File, Form, Header, HTTPException, Query, Request, UploadFile
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import PlainTextResponse, Response

from .audit import Engine, decide, export_markdown, final_text, get_rewrites, run_audit
from .pdf_report import build_pdf
from .chunking import extract_text
from .config import DATA_DIR, get_settings
from .schemas import (
    Audit,
    AuditRequest,
    DecisionRequest,
    DemoDraft,
    DocumentInfo,
    RewriteResponse,
)

settings = get_settings()
_WORKSPACE_RE = re.compile(r"^[A-Za-z0-9_-]{6,40}$")


class RateGate:
    """Tiny sliding-window limiter so one visitor cannot burn the shared free-tier LLM quota."""

    def __init__(self, limit: int, window_s: int = 600) -> None:
        self.limit, self.window = limit, window_s
        self._hits: dict[str, deque[float]] = defaultdict(deque)

    def allow(self, key: str) -> bool:
        now = time.monotonic()
        q = self._hits[key]
        while q and now - q[0] > self.window:
            q.popleft()
        if len(q) >= self.limit:
            return False
        q.append(now)
        return True


engine: Engine
gate = RateGate(settings.llm_audits_per_10min)


@asynccontextmanager
async def lifespan(_: FastAPI):
    global engine
    engine = Engine(settings)
    # Warm the demo workspace (loads the embedding model) so the first judge is not the one waiting.
    await asyncio.to_thread(engine.manager.get, "demo")
    yield


app = FastAPI(title="TrueMark API", version="0.2.0", lifespan=lifespan)
app.add_middleware(
    CORSMiddleware,
    allow_origins=settings.cors_origins,
    allow_methods=["*"],
    allow_headers=["*"],
    expose_headers=["Content-Disposition"],
)


def _ws(x_workspace: str | None) -> str:
    return x_workspace if x_workspace and _WORKSPACE_RE.match(x_workspace) else "demo"


def _client_key(request: Request) -> str:
    fwd = request.headers.get("x-forwarded-for")
    return (fwd.split(",")[0].strip() if fwd else (request.client.host if request.client else "unknown"))


def _get_audit(audit_id: str, workspace_id: str) -> Audit:
    audit = engine.store.get(audit_id, workspace_id)
    if audit is None:
        raise HTTPException(404, "Audit not found. It may have expired; run the audit again.")
    return audit


# ------------------------------------------------------------------ health & demo data


@app.get("/health")
async def health():
    ws = engine.manager.get("demo")
    return {
        "status": "ok",
        "llm": {
            "provider": settings.llm_provider,
            "live": engine.llm.live,
            "model": getattr(getattr(engine.llm, "_inner", None), "model", None),
        },
        "retrieval_backend": ws.backend,
        "rules": len(engine.rules),
    }


@app.get("/samples", response_model=list[DemoDraft])
async def samples():
    return json.loads((DATA_DIR / "demo_drafts.json").read_text(encoding="utf-8"))


# ------------------------------------------------------------------ knowledge base


@app.get("/documents", response_model=list[DocumentInfo])
async def list_documents(x_workspace: str | None = Header(default=None)):
    ws = engine.manager.get(_ws(x_workspace))
    return [DocumentInfo(**i.__dict__) for i in ws.doc_infos()]


@app.post("/ingest", response_model=DocumentInfo)
async def ingest(
    file: UploadFile = File(...),
    doc_type: str = Form("facts"),
    x_workspace: str | None = Header(default=None),
):
    if doc_type not in ("guideline", "facts"):
        raise HTTPException(422, "doc_type must be 'guideline' or 'facts'.")
    data = await file.read(settings.max_upload_bytes + 1)
    if len(data) > settings.max_upload_bytes:
        raise HTTPException(413, f"File too large (limit {settings.max_upload_bytes // 1024 // 1024} MB).")
    try:
        text = extract_text(file.filename or "upload.txt", data)
        ws = engine.manager.get(_ws(x_workspace))
        info = await asyncio.to_thread(
            engine.manager.add_document, ws, file.filename or "Uploaded document", doc_type, text
        )
    except ValueError as exc:
        raise HTTPException(422, str(exc)) from exc
    return DocumentInfo(**info.__dict__)


@app.delete("/documents/{doc_id}", status_code=204)
async def delete_document(doc_id: str, x_workspace: str | None = Header(default=None)):
    ws = engine.manager.get(_ws(x_workspace))
    try:
        await asyncio.to_thread(engine.manager.remove_document, ws, doc_id)
    except KeyError:
        raise HTTPException(404, "Document not found.")
    except ValueError as exc:
        raise HTTPException(422, str(exc)) from exc
    return Response(status_code=204)


# ------------------------------------------------------------------ audit workflow


@app.post("/audit", response_model=Audit)
async def audit_endpoint(req: AuditRequest, request: Request, x_workspace: str | None = Header(default=None)):
    if not req.draft.strip():
        raise HTTPException(422, "Paste some copy to audit.")
    if len(req.draft) > settings.max_draft_chars:
        raise HTTPException(
            413, f"Draft is too long ({len(req.draft)} characters). The demo limit is {settings.max_draft_chars}."
        )
    allow_llm = True
    if req.use_llm and engine.llm.live:
        allow_llm = gate.allow(_client_key(request))
    return await run_audit(engine, _ws(x_workspace), req, allow_llm)


@app.get("/audit/{audit_id}", response_model=Audit)
async def get_audit(audit_id: str, x_workspace: str | None = Header(default=None)):
    return _get_audit(audit_id, _ws(x_workspace))


@app.post("/audit/{audit_id}/findings/{finding_id}/rewrite", response_model=RewriteResponse)
async def rewrite_endpoint(
    audit_id: str, finding_id: str, request: Request, x_workspace: str | None = Header(default=None)
):
    audit = _get_audit(audit_id, _ws(x_workspace))
    if engine.llm.live and not gate.allow(_client_key(request) + ":rewrite"):
        raise HTTPException(429, "Too many rewrite requests. Please wait a few minutes.")
    try:
        return await get_rewrites(engine, audit, finding_id)
    except KeyError:
        raise HTTPException(404, "Finding not found.")


@app.post("/audit/{audit_id}/findings/{finding_id}/decision", response_model=Audit)
async def decision_endpoint(
    audit_id: str, finding_id: str, req: DecisionRequest, x_workspace: str | None = Header(default=None)
):
    audit = _get_audit(audit_id, _ws(x_workspace))
    try:
        decide(engine, audit, finding_id, req)
    except KeyError:
        raise HTTPException(404, "Finding not found.")
    except ValueError as exc:
        raise HTTPException(422, str(exc)) from exc
    return audit


@app.get("/audit/{audit_id}/final")
async def final_endpoint(audit_id: str, x_workspace: str | None = Header(default=None)):
    audit = _get_audit(audit_id, _ws(x_workspace))
    text, skipped = final_text(audit)
    return {"final_text": text, "needs_approval": audit.needs_approval, "skipped_edits": skipped}


@app.get("/audit/{audit_id}/export")
async def export_endpoint(
    audit_id: str,
    format: str = Query("md", pattern="^(md|json|txt|pdf)$"),
    x_workspace: str | None = Header(default=None),
):
    audit = _get_audit(audit_id, _ws(x_workspace))
    engine.store.log(audit, "exported", detail=format)
    name = f"truemark-audit-{audit.audit_id}"
    if format == "json":
        body = json.dumps(
            {**audit.model_dump(), "final_text": final_text(audit)[0]}, indent=2, ensure_ascii=False
        )
        return Response(body, media_type="application/json",
                        headers={"Content-Disposition": f'attachment; filename="{name}.json"'})
    if format == "pdf":
        text, skipped = final_text(audit)
        return Response(build_pdf(audit, text, skipped), media_type="application/pdf",
                        headers={"Content-Disposition": f'attachment; filename="{name}.pdf"'})
    if format == "txt":
        return PlainTextResponse(final_text(audit)[0],
                                 headers={"Content-Disposition": f'attachment; filename="{name}.txt"'})
    return PlainTextResponse(export_markdown(audit), media_type="text/markdown",
                             headers={"Content-Disposition": f'attachment; filename="{name}.md"'})
